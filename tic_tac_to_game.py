def display_board(board):
    print("\n\n")
    print(" " + board[7] + " | " + board[8] + " | " + board[9])
    print("-----------")
    print(" " + board[4] + " | " + board[5] + " | " + board[6])
    print("-----------")
    print(" " + board[1] + " | " + board[2] + " | " + board[3])

def player_input():
    marker = ''
    while not (marker == 'X' or marker == 'O'):
        marker = input('Player 1: Do you want to be X or O? ').upper()

    if marker == 'X':
        return ('X', 'O')
    else:
        return ('O', 'X')

def place_marker(board, marker, position):
    board[position] = marker

def win_check(board, mark):
    return ((board[7] == mark and board[8] == mark and board[9] == mark) or # across the top
            (board[4] == mark and board[5] == mark and board[6] == mark) or # across the middle
            (board[1] == mark and board[2] == mark and board[3] == mark) or # across the bottom
            (board[7] == mark and board[4] == mark and board[1] == mark) or # down the left side
            (board[8] == mark and board[5] == mark and board[2] == mark) or # down the middle
            (board[9] == mark and board[6] == mark and board[3] == mark) or # down the right side
            (board[7] == mark and board[5] == mark and board[3] == mark) or # diagonal
            (board[9] == mark and board[5] == mark and board[1] == mark)) # diagonal

import random

def choose_first():
    if random.randint(0, 1) == 0:
        return 'Player 2'
    else:
        return 'Player 1'

def space_check(board, position):
    return board[position] == ' '

def full_board_check(board):
    for i in range(1, 10):
        if space_check(board, i):
            return False
    return True

def player_choice(board):
    position = 0
    while position not in [1, 2, 3, 4, 5, 6, 7, 8, 9] or not space_check(board, position):
        try:
            position = int(input('Choose your next position: (1-9) '))
        except ValueError:
            print("Invalid input. Please enter a number between 1 and 9.")
    return position

def computer_choice(board, player_marker, opponent_marker):
    possible_moves = []
    for i in range(1, 10):
        if space_check(board, i):
            possible_moves.append(i)

    # Check for winning move for computer
    for move in possible_moves:
        board_copy = list(board)
        board_copy[move] = opponent_marker
        if win_check(board_copy, opponent_marker):
            return move

    # Check for winning move for player to block
    for move in possible_moves:
        board_copy = list(board)
        board_copy[move] = player_marker
        if win_check(board_copy, player_marker):
            return move

    # Try to take corners
    corners = [1, 3, 7, 9]
    available_corners = [move for move in possible_moves if move in corners]
    if available_corners:
        return random.choice(available_corners)

    # Try to take the center
    if 5 in possible_moves:
        return 5

    # Take any available side
    sides = [2, 4, 6, 8]
    available_sides = [move for move in possible_moves if move in sides]
    if available_sides:
        return random.choice(available_sides)

    return random.choice(possible_moves) # Fallback to any random move

def replay():
    return input('Do you want to play again? Enter Yes or No: ').lower().startswith('y')

print('Welcome to Tic Tac Toe!')

while True:
    theBoard = [' '] * 10
    player1_marker, player2_marker = player_input()

    game_mode = ''
    while game_mode not in ['H', 'C']:
        game_mode = input('Do you want to play against another Human (H) or Computer (C)? ').upper()

    turn = choose_first()
    print(turn + ' will go first.')

    game_on = True

    while game_on:
        if turn == 'Player 1':
            display_board(theBoard)
            position = player_choice(theBoard)
            place_marker(theBoard, player1_marker, position)

            if win_check(theBoard, player1_marker):
                display_board(theBoard)
                print('Congratulations! Player 1 has won the game!')
                game_on = False
            else:
                if full_board_check(theBoard):
                    display_board(theBoard)
                    print('The game is a draw!')
                    game_on = False
                else:
                    turn = 'Player 2'

        else: # Player 2's turn
            if game_mode == 'H': # Human Player 2
                display_board(theBoard)
                position = player_choice(theBoard)
            else: # Computer Player
                print("Computer's Turn...")
                position = computer_choice(theBoard, player1_marker, player2_marker)

            place_marker(theBoard, player2_marker, position)

            if win_check(theBoard, player2_marker):
                display_board(theBoard)
                print('Congratulations! ' + ('Player 2' if game_mode == 'H' else 'Computer') + ' has won the game!')
                game_on = False
            else:
                if full_board_check(theBoard):
                    display_board(theBoard)
                    print('The game is a draw!')
                    game_on = False
                else:
                    turn = 'Player 1'

    if not replay():
        break

