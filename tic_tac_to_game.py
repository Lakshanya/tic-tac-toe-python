def win_check(board_state, mark):
    winning_combinations = [
        [7, 8, 9], [4, 5, 6], [1, 2, 3], # rows
        [7, 4, 1], [8, 5, 2], [9, 6, 3], # columns
        [7, 5, 3], [9, 5, 1]             # diagonals
    ]
    for combo in winning_combinations:
        if (board_state[combo[0]] == mark and
            board_state[combo[1]] == mark and
            board_state[combo[2]] == mark):
            return combo # Return the winning combination
    return None # No win

def space_check(board_state, position):
    return board_state[position] == ' '

